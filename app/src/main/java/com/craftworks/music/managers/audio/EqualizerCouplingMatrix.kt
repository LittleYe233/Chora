package com.craftworks.music.managers.audio

/**
 * Inter-band crosstalk compensation for the 10-band equalizer.
 *
 * Cascading peaking biquads at 1-octave spacing do not sum linearly: each
 * band's filter also boosts (or, in cuts, attenuates) its neighbors' center
 * frequencies, so a naive cascade overshoots the requested curve. This file
 * precomputes the inverse of the 10x10 coupling matrix and applies it at
 * control rate: the per-biquad target gains become `M^-1 * userGains`, which
 * cancels the inter-band interference and makes the measured response match
 * the user's requested gains at every band center.
 *
 * The inverse matrix is a compile-time constant because every parameter it
 * depends on is fixed for the app's life: the 10 center frequencies of
 * [EQ_BAND_FREQUENCIES_HZ] (31 Hz .. 16 kHz), the peaking Q of sqrt(2f)
 * (~1.414), and the nominal 44100 Hz reference sample rate. If any of those
 * change, the matrix must be regenerated by the same procedure described in
 * [INVERSE_COUPLING_MATRIX].
 *
 * This object is pure Kotlin math with no Android or Media3 dependencies.
 */
object EqualizerCouplingMatrix {

    /**
     * Reference sample rate the coupling matrix was computed for. The equalizer
     * runs at the device's actual rate (typically 44100 or 48000 Hz); the small
     * mismatch is negligible at the band widths involved and keeps the matrix a
     * compile-time constant, as the reference design intends.
     */
    const val REFERENCE_SAMPLE_RATE_HZ = 44100f

    /**
     * 10x10 inverse coupling matrix, row-major over [EQ_BAND_FREQUENCIES_HZ]
     * order. Entry `[i][j]` is the compensation applied to band `i`'s gain when
