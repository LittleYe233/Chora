    /**
     * Computes `INVERSE_COUPLING_MATRIX * [targets]` and stores the result in
     * [into]. Both arrays must have 10 elements. Allocation-free, so it is safe
     * to call from control-rate code; the audio-rate path never touches this.
     */
    fun compensatedGains(targets: FloatArray, into: FloatArray) {
        var i = 0
        while (i < 10) {
            val row = INVERSE_COUPLING_MATRIX[i]
            var acc = 0f
            var j = 0
            while (j < 10) {
                acc += row[j] * targets[j]
                j++
            }
            into[i] = acc
            i++
        }
    }
}
