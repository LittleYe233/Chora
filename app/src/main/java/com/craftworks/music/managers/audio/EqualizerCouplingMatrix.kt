     *
     * Generation (done once with a plain-JVM tool, not at runtime):
     *  1. For each band j, design a peaking biquad at its center frequency with
     *     a 1 dB probe gain (RBJ formulas, Q = sqrt(2), fs = 44100).
     *  2. Sample |H(e^jw)| of that filter at every band center i and store
     *     `M[i][j] = 20*log10(|H|)`; the diagonal is exactly 1.0, off-diagonal
     *     entries are the crosstalk.
     *  3. Invert M (Gauss-Jordan with partial pivoting; M is diagonally
     *     dominant and non-singular, so the inverse equals the pseudo-inverse
     *     used by the reference implementation).
